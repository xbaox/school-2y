/* 2.8.0, A6: промпт урока — план получает урок, стретч L3 из контента берётся
   как есть, слова урока (lesson.words) печатаются для ИТОГа.

   - stagesBlock видит урок: опорных заданий меньше, чем мест ступени, — ИИ
     добирает недостающие по теме (ветка была с 2.7.1, но урок до неё не доходил);
   - стретч L3 из контента уже конкурсного уровня — план не велит его усиливать;
   - «Слова урока для ИТОГа: …» — и правило ИТОГа «3–5 слов из списка урока»;
     без списка — термины курса по теме, как было.
   Промпты уроков без words и без L3 не меняются (проверено посимвольно на
   живой копии: 59 уроков, 355 промптов). */

(function () {
  'use strict';

  var T = '2026-10-05';

  function fresh(stage) {
    State.reset();
    State.syncContent();
    State.setMode('school');
    State.setStage(stage || 'S0');
  }

  function fin(p) { return p.slice(p.indexOf('[ФИНАЛ] —')); }

  describe('2.8.0 A6: план видит урок — опорных меньше мест ступени, ИИ добирает по теме', function () {
    fresh('S1');
    var p = PROMPTS.lesson('B7.1', { today: T });
    ok(p.indexOf('Опорных заданий дано меньше, чем просит ступень (основа 4 из 7, стретч 1 из 2): ' +
      'недостающие составь по образцу опорных — та же тема и тот же уровень.') > 0, 'Б7.1 на S1: 4 из 7');
    fresh('S0');
    eq(PROMPTS.lesson('B7.1', { today: T }).indexOf('Опорных заданий дано меньше'), -1, 'на S0 мест 4 — хватает');
    eq(PROMPTS.lesson('B11.1', { today: T }).indexOf('Опорных заданий дано меньше'), -1,
      'урок без заданий — фолбэк, а не «меньше»');
  });

  describe('2.8.0 A6: стретч L3 из контента — как есть', function () {
    fresh('S0');
    var p = PROMPTS.lesson('B9.1', { today: T });
    ok(p.indexOf('Стретч дан в [ОПОРНЫЕ ЗАДАНИЯ] (L3) — бери его как есть, условие не меняй и не усиливай; ') > 0,
      'план берёт стретч как есть');
    eq(p.indexOf('усиль её до конкурсного уровня'), -1, 'и не велит усиливать');
  });

  describe('2.8.0 A6: слова урока — в [ФИНАЛ], правило ИТОГа — из списка', function () {
    fresh('S0');
    var f = fin(PROMPTS.lesson('B9.1', { today: T }));
    var w = CONTENT.lesson('B9.1').words;
    var line = 'Слова урока для ИТОГа: ' + w.map(function (x) { return x.en + ' — ' + x.ru; }).join('; ');
    ok(f.indexOf(line) > 0, 'список слов урока напечатан');
    ok(f.indexOf('В строке «Слова» — от 3 до 5 слов из списка «Слова урока для ИТОГа», никогда не больше пяти.') > 0,
      'правило — из списка урока');
    eq(f.indexOf('только термины курса Онтарио'), -1, 'прежнего правила у урока со списком нет');
    ok(f.indexOf(line) < f.indexOf('=== ИТОГ УРОКА B9.1 ==='), 'список — до шаблона, вне блока');

    var c = fin(PROMPTS.lesson('B53.4', { today: T }));
    ok(c.indexOf('Слова урока для ИТОГа: two-digit number — двузначное число') > 0, 'и у К.4');

    var b7 = fin(PROMPTS.lesson('B7.1', { today: T }));
    eq(b7.indexOf('Слова урока для ИТОГа'), -1, 'у Б7.1 списка нет');
    ok(b7.indexOf('В строке «Слова» — от 3 до 5 терминов, никогда не больше пяти; только термины курса Онтарио ' +
      'по теме урока, общих английских слов там нет.') > 0, 'и правило прежнее');
  });

  describe('2.8.0 A6: список слов, переписанный ИИ внутрь блока, — не данные итога', function () {
    fresh('S0');
    var p = PROMPTS.lesson('B9.1', { today: T });
    var f = fin(p).split('\n');
    var list = f.filter(function (l) { return l.indexOf('Слова урока для ИТОГа') === 0; })[0];
    var rule = f.filter(function (l) { return l.indexOf('В строке «Слова»') === 0; })[0];
    var itog = ['=== ИТОГ УРОКА B9.1 ===', 'Пройдено: т', 'Уровень: L2', 'Счёт: 8/10', 'Стретч: —',
      'Слова (3–5): divisor — делитель; quotient — частное; remainder — остаток', list, '- ' + rule,
      'Долги: нет', '=== КОНЕЦ ==='].join('\n');
    var r = PROMPTS.parse(itog, 'B9.1');
    eq(r.words.map(function (x) { return x.en; }), ['divisor', 'quotient', 'remainder'], 'три слова — список и правило пропущены');
  });

  State.reset();
  State.syncContent();
})();
