/* 2.7.1 — хотфикс промпта: длина сообщения, слово «время», обратная ветка,
   стретч ⭐⭐ конкурсного уровня, видео только до урока, правило 22.

   Стретч перестал быть «третьим баллом»: он вне счёта, всегда предлагается
   и считается отдельно — иначе взятая олимпиадная задача нигде не оставалась. */

(function () {
  'use strict';

  function school(stage) {
    State.reset();
    State.syncContent();
    State.setMode('school');
    State.s.step.cycleStart = '2026-09-08';
    State.setStage(stage || 'S0');
  }

  function summary(over) {
    return Object.assign({
      score: 8, level: 'L2', topics: 'тема',
      words: [], debts: [], cleared: [], warmup: [], checklist: null, stretch: null,
      writing: '', raw: ''
    }, over || {});
  }

  var T = '2026-09-14';

  /* ============ 1–4, 7: правила контракта ============ */

  describe('2.7.1 контракт: новые требования в правилах', function () {
    school('S0');
    var p = PROMPTS.lesson('B7.1', { today: T });

    ok(p.indexOf('Одно сообщение преподавателя — не длиннее 10 строк, ' +
      'кроме образца решения по правилу 7.') > 0, 'правило 2: длина сообщения');
    ok(p.indexOf('Слово «время» = таймер ученика прозвенел: сразу Выход ' +
      '(пересказ, что взял, связка) и ИТОГ, урок засчитан полностью.') > 0,
      'правило 3: слово «время»');
    ok(p.indexOf('Чистовик — один.') > 0, 'правило 8: один чистовик');
    ok(p.indexOf('Обратная ветка: два полных балла подряд в основе → ' +
      'к следующему заданию основы после ответа добавляется усиление на 1–2 минуты: ' +
      'обратная задача, параметр, «докажи» или «а что если»; в счёт не идёт.') > 0,
      'правило 10: обратная ветка');
    ok(p.indexOf('22. Программа, расписание блоков, уровни и ступени в уроке ' +
      'не обсуждаются — ответ «это к Архитектору», дальше по плану.') > 0, 'правило 22');
  });

  describe('2.7.1 контракт: правило 20 не тронуто', function () {
    school('S0');
    var p = PROMPTS.lesson('B7.1', { today: T });
    ok(p.indexOf('20. Приоритеты: сон > школа > урок. Если ученик пишет, что поздно ' +
      'или завтра тест — предложить минималку и закончить.') > 0, 'приоритеты на месте');
  });

  /* ============ 5: стретч ⭐⭐ ============ */

  describe('2.7.1 стретч: конкурсный уровень, всегда предлагается', function () {
    school('S0');
    // 2.8.0 (A6): у Б7.1 стретч L3 есть в контенте — берётся как есть, без «усиль»;
    // урок без заданий (Б11.1) — прежняя формулировка
    var p = PROMPTS.lesson('B7.1', { today: T });
    ok(p.indexOf('Стретч ⭐⭐ — задача конкурсного уровня (CSMC часть B / Euclid) ' +
      'по теме урока, всегда предлагается: «⭐⭐ или закрываем?» ' +
      'Отказ ничего не снимает; решение — ⭐ в журнал. ' +
      'Стретч дан в [ОПОРНЫЕ ЗАДАНИЯ] (L3) — бери его как есть, условие не меняй и не усиливай; ' +
      'решение показываешь после попытки.') > 0, 'формулировка целиком');
    eq(p.indexOf('усиль её до конкурсного уровня'), -1, 'стретч из контента не усиливается');
    ok(PROMPTS.lesson('B11.1', { today: T }).indexOf(
      'Если в опорных заданиях есть L3 — это база: усиль её до конкурсного уровня. ' +
      'Если опорных нет — составь сам, предварительно решив до конца; ' +
      'решение показываешь после попытки.') > 0, 'урок без заданий — прежняя формулировка');
    eq(p.indexOf('⭐ на 3 балла'), -1, 'обещания трёх баллов за стретч больше нет');
    // и в счёт он по-прежнему не входит
    ok(p.indexOf('разогрев и стретч в счёт не входят') > 0, 'стретч вне счёта');
  });

  describe('2.7.1 стретч: строка в шаблоне ИТОГа и её разбор', function () {
    school('S0');
    var p = PROMPTS.lesson('B7.1', { today: T });
    var f = p.slice(p.indexOf('=== ИТОГ УРОКА'));
    ok(f.indexOf('Стретч: ✓ | ✗ | —') > 0, 'строка в шаблоне есть');
    ok(f.indexOf('Счёт: N/10') < f.indexOf('Стретч:'), 'и стоит сразу после счёта');

    eq(PROMPTS.parseStretch('✓'), true, 'галочка — взят');
    eq(PROMPTS.parseStretch('✗'), false, 'крестик — не взят');
    eq(PROMPTS.parseStretch('—'), null, 'прочерк — нет ответа');
    eq(PROMPTS.parseStretch(''), null, 'пусто — тоже');
    eq(PROMPTS.parseStretch('✓ | ✗ | —'), null, 'незаполненный шаблон не читается как взятый');
  });

  describe('2.7.1 стретч: счётчик решённых живёт в состоянии', function () {
    school('S0');
    eq(State.stretchCount(), 0, 'вначале ноль');

    function itog(id, mark) {
      return PROMPTS.parse([
        '=== ИТОГ УРОКА ' + id + ' ===', 'Пройдено: т', 'Уровень: L2', 'Счёт: 8/10',
        'Стретч: ' + mark, '=== КОНЕЦ ==='
      ].join('\n'));
    }

    var p1 = itog('B7.1', '✓');
    eq(p1.stretch, true, 'итог разобран');
    State.applySummary('B7.1', p1, { date: '2026-09-10' });
    eq(State.stretchCount(), 1, 'один взят');

    // повторная вставка того же итога счётчик не двигает
    State.applySummary('B7.1', p1, { date: '2026-09-10' });
    eq(State.stretchCount(), 1, 'повторная вставка ничего не удвоила');

    State.applySummary('B7.2', itog('B7.2', '✗'), { date: '2026-09-11' });
    eq(State.stretchCount(), 1, 'отказ счётчик не двигает');

    State.applySummary('B7.3', itog('B7.3', '✓'), { date: '2026-09-12' });
    eq(State.stretchCount(), 2, 'второй взят');

    // исправление итога с ✓ на ✗ снимает засчитанный стретч
    State.applySummary('B7.3', itog('B7.3', '✗'), { date: '2026-09-12' });
    eq(State.stretchCount(), 1, 'правка итога учтена');
  });

  // карточка урока есть только в будни: в воскресенье радар-день, в субботу
  // день у блока К. Кейс про звёзды — про будни, дату фиксируем
  describe('2.7.1 стретч: ⭐N рядом со счётом урока на «Сегодня»', function () { withToday(T, function () {
    school('S0');
    var t = State.today();
    eq(Lesson.card(t).indexOf('⭐'), -1, 'без взятых стретчей звёзд нет');

    State.s.stats.stretchDone = 3;
    var card = Lesson.card(t);
    ok(card.indexOf('⭐3') > 0, 'счётчик виден на карточке урока');
    ok(card.indexOf('прошлых уроков дорожки нет · ⭐3') > 0 ||
      card.indexOf('/10 · ⭐3') > 0, 'и стоит рядом со счётом урока');
  }); });

  /* ============ 6: видео ============ */

  describe('2.7.1 видео: только до урока, О1 — по факту просмотра', function () {
    school('S0');
    var p = PROMPTS.lesson('B7.1', { today: T });      // у Б7.1 видео задано
    ok(p.indexOf('Видео — только до урока, по карточке «Что смотреть». ' +
      'Если «Видео просмотрено: нет» — урок идёт без него, определения даёт [ГЛОССАРИЙ]; ' +
      'О1 проверяется только когда видео просмотрено.') > 0, 'формулировка целиком');
    eq(p.indexOf('отправь смотреть с заданием'), -1, 'урок больше не останавливается ради видео');
    eq(p.indexOf('вопрос ученика после видео обязателен'), -1, 'безусловного требования О1 нет');
  });

  /* ============ 8: фолбэк без заданий ============ */

  describe('2.7.1 фолбэк: урок без tasks ведётся по правилам', function () {
    school('S0');
    var p = PROMPTS.lesson('B11.1', { today: T });     // задания Б11 приедут пакетом контента (Б9 — с 2.8.0)
    ok(p.indexOf('вести по фокусу: 4 основных задания уровня L2 школьного; ' +
      'усиление и ⭐⭐ — по правилам') > 0, 'фолбэк называет и усиление, и стретч');
  });

  /* ============ 9: кнопка ступени ============ */

  describe('2.7.1 ступень: средний 8.9 за четыре урока показывает кнопку', function () {
    school('S0');
    [9, 9, 9, 8.6].forEach(function (sc, i) {
      State.applySummary('B7.' + (i + 1), summary({ score: sc }),
        { date: U.addDays(T, -(i + 1)) });
    });
    eq(State.readyForNextStage(T), true, 'условие выполнено: 8.9 по четырём урокам');
    eq(State.nextStageOffer(T), 'S1', 'кнопка предлагает S1');
    ok(App.stageOffer(T).indexOf('Стало легко → S1') > 0, 'и она на экране');
    eq(State.stageName(), 'S0', 'но сама ступень не поднялась — только по нажатию');
    State.setMode('summer');
  });

  State.reset();
  State.syncContent();
})();
