/* Этап 7.2 (релиз 2.6.0): списочные поля «ИТОГА УРОКА» не рвут математику.
   Раньше `.replace(/\s(\d+)[).]\s/g, '\n')` делал границей элемента любые
   «пробел + цифры + точка-или-скобка + пробел», и само число исчезало. */

(function () {
  'use strict';

  function parse(fields) {
    var lines = ['=== ИТОГ УРОКА B2.2 ===', 'Пройдено: системы', 'Уровень: L2', 'Счёт: 7/10'];
    Object.keys(fields).forEach(function (k) { lines.push(k + ': ' + fields[k]); });
    lines.push('=== КОНЕЦ ===');
    return PROMPTS.parse(lines.join('\n'));
  }

  /* Каждый кейс проверяется во всех четырёх списочных полях сразу. */
  var LIST_FIELDS = [
    { label: 'В разогрев', key: 'warmup' },
    { label: 'Долги', key: 'debts' },
    { label: 'Погашено', key: 'cleared' }
  ];

  function eachField(text, expect, name) {
    LIST_FIELDS.forEach(function (f) {
      var o = {};
      o[f.label] = text;
      var p = parse(o);
      eq(p[f.key], expect, name + ' — поле «' + f.label + '»');
    });
    // слова: тот же текст как перевод, английская часть слева
    var p = parse({ 'Слова': 'expr — ' + text });
    eq(p.words.length, 1, name + ' — поле «Слова»: элемент один');
    eq(p.words[0].ru, text, name + ' — поле «Слова»: перевод цел');
  }

  describe('парсер 7.2: уравнение в конце предложения не рвётся', function () {
    eachField('что даёт уравнение 2x − 3y = 0. Объясни смысл',
      ['что даёт уравнение 2x − 3y = 0. Объясни смысл'], 'формула + точка + текст');
  });

  describe('парсер 7.2: «= 0.» в самом конце строки', function () {
    eachField('приведи систему к виду 2x − 3y = 0.',
      ['приведи систему к виду 2x − 3y = 0.'], 'формула в конце поля');
  });

  describe('парсер 7.2: числа-перечисления внутри текста', function () {
    eachField('назови 3 признака подобия и 2 следствия из них',
      ['назови 3 признака подобия и 2 следствия из них'], 'числа в тексте');
    eachField('проверь шаги 1. 2. 3. в решении',
      ['проверь шаги 1. 2. 3. в решении'], 'нумерация шагов внутри фразы');
  });

  describe('парсер 7.2: скобки и десятичные дроби целы', function () {
    eachField('вычисли (x + 2) при x = 3', ['вычисли (x + 2) при x = 3'], 'закрывающая скобка после цифры');
    eachField('округли 12.5 и 0.75 до десятых', ['округли 12.5 и 0.75 до десятых'], 'десятичные дроби');
    eachField('подставь x = 1.5 в y = 2x + 3.', ['подставь x = 1.5 в y = 2x + 3.'], 'дробь и точка в конце');
  });

  describe('парсер 7.2: отрицательные числа не теряют знак', function () {
    eachField('-3 < x < 5 — запиши промежуток', ['-3 < x < 5 — запиши промежуток'], 'ведущий минус');
    // а настоящий маркер списка (с пробелом после) по-прежнему срезается
    var p = parse({ 'Долги': '- путает знак наклона\n- теряет единицы' });
    eq(p.debts, ['путает знак наклона', 'теряет единицы'], 'дефис-маркер с пробелом срезан');
  });

  describe('парсер 7.2: перевод строки остаётся разделителем', function () {
    var p = parse({ 'В разогрев': 'реши 2x − 3y = 0\n4x + y = 1\nпроверь ответ подстановкой' });
    eq(p.warmup, ['реши 2x − 3y = 0', '4x + y = 1', 'проверь ответ подстановкой'],
      'три строки — три элемента, формулы целы');
  });

  describe('парсер 7.2: точка с запятой остаётся разделителем', function () {
    var p = parse({ 'Слова': 'slope — наклон; vertex — вершина' });
    eq(p.words.length, 2, 'слова по «;»');
    var w = parse({ 'В разогрев': 'что такое slope?; как найти y-intercept?' });
    eq(w.warmup.length, 2, 'вопросы по «;» — так их и пишет ИИ');
  });

  describe('парсер 7.2: испорченный разогрев больше не уезжает в промпт', function () {
    State.reset();
    State.syncContent();
    var p = parse({ 'В разогрев': 'что даёт 2x − 3y = 0. Объясни смысл' });
    State.applySummary('B2.1', p, { date: '2026-08-25' });

    var prompt = PROMPTS.lesson('B2.2', { today: '2026-08-26' });
    ok(prompt.indexOf('что даёт 2x − 3y = 0. Объясни смысл') > 0,
      'вопрос доехал до блока ПАМЯТЬ целиком');
    eq(prompt.indexOf('что даёт 2x − 3y ='), prompt.indexOf('что даёт 2x − 3y = 0. Объясни смысл'),
      'огрызка без правой части в промпте нет');
  });
})();
