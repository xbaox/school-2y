/* Светофор темпа блока — раздел 7.5 ТЗ. */

describe('темп: норматив', function () {
  // 2.8.0 (A3): норматив — на учебный день; «Школа» — те же 2 урока в неделю из пяти дней
  eq(PACE.rate('school'), 2 / 5, 'школа — 2 урока в неделю (из пяти учебных дней)');
  eq(PACE.rate('summer'), 1, 'до школы — 1 урок в учебный день');
});

describe('темп: цвета', function () {
  function st(remaining, deadline, today, mode) {
    return PACE.status({ remaining: remaining, deadline: deadline, today: today, mode: mode || 'summer' });
  }

  // до школы: 1 урок в учебный день (пн–сб), значит 2 урока — ровно 2 учебных дня.
  // 2.8.0 (A3): дни — учебные, воскресенье не считается
  eq(st(2, '2026-08-28', '2026-08-24').color, 'green', 'лето: 2 урока за 5 учебных дней — зелёный');
  eq(st(2, '2026-08-28', '2026-08-24').text, 'запас 3 дня', 'запас считается в учебных днях');

  // впритык: доступно ровно столько, сколько нужно
  eq(st(2, '2026-08-25', '2026-08-24').color, 'yellow', 'лето: 2 урока за 2 учебных дня — впритык');
  eq(st(2, '2026-08-25', '2026-08-24').text, 'впритык', 'текст жёлтого');

  eq(st(4, '2026-08-25', '2026-08-24').color, 'red', 'лето: 4 урока за 2 учебных дня — красный');
  eq(st(4, '2026-08-25', '2026-08-24').text, 'не успеть без доп. уроков', 'текст красного');

  // суббота летом — учебный день, воскресенье — нет
  eq(st(1, '2026-08-22', '2026-08-22').color, 'yellow', 'лето: срок в субботу — один учебный день, впритык');
  eq(st(1, '2026-08-23', '2026-08-23').color, 'red', 'лето: срок в воскресенье — учебных дней нет');
  eq(st(1, '2026-08-23', '2026-08-23').overdue, false, 'но это ещё не просрочка');

  // школа: 2 урока в неделю → 4 урока ≈ 14 дней
  eq(st(4, '2026-09-25', '2026-09-08', 'school').color, 'green', 'школа: 4 урока за 18 дней — зелёный');
  eq(st(4, '2026-09-20', '2026-09-08', 'school').color, 'red', 'школа: 4 урока за 13 дней — красный');
  eq(st(4, '2026-09-21', '2026-09-08', 'school').color, 'yellow', 'школа: 4 урока ровно за 14 дней — впритык');
  eq(st(4, '2026-09-22', '2026-09-08', 'school').color, 'green', 'школа: 15 дней — уже запас');

  // блок закрыт
  eq(st(0, '2026-08-20', '2026-08-25').done, true, 'нет остатка — блок закрыт');
  eq(st(0, '2026-08-20', '2026-08-25').color, 'green', 'закрытый блок зелёный даже после дедлайна');

  // просрочка
  eq(st(1, '2026-08-20', '2026-08-22').color, 'red', 'дедлайн позади — красный');
  eq(st(1, '2026-08-20', '2026-08-22').overdue, true, 'помечен как просроченный');
  eq(st(1, '2026-08-20', '2026-08-22').text, 'просрочен на 2 дня', 'считает дни просрочки');
  eq(st(1, '2026-08-22', '2026-08-22').overdue, false, 'дедлайн сегодня — ещё не просрочен');

  // без дедлайна не падаем
  eq(st(3, null, '2026-08-22').text, 'без дедлайна', 'пустой дедлайн обрабатывается мягко');
});

describe('темп: строка для карточки', function () {
  var s = PACE.status({ remaining: 2, deadline: '2026-08-28', today: '2026-08-24', mode: 'summer' });
  eq(PACE.line(s, '2026-08-28'), 'до 28 авг · 🟢 запас 3 дня', 'формат строки из раздела 6.1');
});

describe('2.8.1 B1: последний урок блока — не красный, пока до срока есть учебный день', function () {
  function st(remaining, deadline, today, mode) {
    return PACE.status({ remaining: remaining, deadline: deadline, today: today, mode: mode || 'school' });
  }
  // вопрос 23 отчёта 2.8.0: один урок и два учебных дня — было красным (норма 2/5 = 2,5 дня)
  eq([st(1, '2026-09-18', '2026-09-17').color, st(1, '2026-09-18', '2026-09-17').text],
    ['green', 'запас 1 день'], 'один урок, два учебных дня (чт–пт) — зелёный, запас 1 день');
  eq([st(1, '2026-09-18', '2026-09-18').color, st(1, '2026-09-18', '2026-09-18').text],
    ['yellow', 'впритык'], 'один урок, срок сегодня (пт) — жёлтый');
  eq(st(1, '2026-09-21', '2026-09-19').color, 'yellow', 'сб → срок в пн: один учебный день — впритык');
  eq(st(1, '2026-09-25', '2026-09-19').text, 'запас 4 дня', 'сб → пт: пять учебных дней, запас 4');
  // учебных дней до срока нет — правило не действует, норма как есть
  eq([st(1, '2026-09-20', '2026-09-19').color, st(1, '2026-09-20', '2026-09-19').overdue],
    ['red', false], 'сб → срок в вс: учебных дней нет — красный, но не просрочка');
  eq(st(1, '2026-09-16', '2026-09-19').text, 'просрочен на 3 дня', 'просрочка — как была');
  // остаток больше одного — норма 2/5 без изменений
  eq(st(2, '2026-09-18', '2026-09-14').color, 'yellow', 'два урока за пять учебных дней — впритык (2/5)');
  eq(st(2, '2026-09-17', '2026-09-14').color, 'red', 'два урока за четыре — красный');
  eq(st(1, '2026-08-22', '2026-08-21', 'summer').text, 'запас 1 день', 'лето: как и было (норма 1)');
});
