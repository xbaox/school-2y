describe('парсер 8.4: мягкие ошибки', function () {
  var bad = PROMPTS.parse('просто текст без формата');
  eq(bad.ok, false, 'мусор отклонён');
  ok(/Не вижу формата/.test(bad.error), 'ошибка объясняет, что делать');

  var noScore = PROMPTS.parse('=== ИТОГ УРОКА B1.1 ===\nУровень: L2\n=== КОНЕЦ ===');
  eq(noScore.ok, false, 'без счёта не закрываем');
  ok(/сч[ёе]та/.test(noScore.error), 'сказано, чего не хватает');

  var noLevel = PROMPTS.parse('=== ИТОГ УРОКА B1.1 ===\nСчёт: 7/10\n=== КОНЕЦ ===');
  eq(noLevel.ok, false, 'без уровня не закрываем');
  ok(/уровня/.test(noLevel.error), 'сказано про уровень');

  var minimal = PROMPTS.parse('=== ИТОГ УРОКА B1.1 ===\nСчёт: 7/10\nУровень: L1\n=== КОНЕЦ ===');
  eq(minimal.ok, true, 'счёт + уровень — достаточно');
});

describe('парсер A-09: счёт строго N/10', function () {
  function p(score, level) {
    return PROMPTS.parse('=== ИТОГ УРОКА B1.1 ===\nСчёт: ' + score +
      '\nУровень: ' + (level || 'L2') + '\n=== КОНЕЦ ===');
  }
  eq(p('7/10').score, 7, 'целое N/10');
  eq(p('7.5/10').score, 7.5, 'с точкой');
  eq(p('7,5/10').score, 7.5, 'с запятой');
  eq(p('9 / 10').score, 9, 'с пробелами вокруг дроби');
  eq(p('10/10').score, 10, 'десятка');

  // незаполненный шаблон приезжает от ИИ чаще всего — его нельзя читать как счёт
  eq(p('N/10').ok, false, 'шаблон «N/10» отклонён');
  ok(/сч[ёе]та/.test(p('N/10').error), 'сказано, что не хватает счёта');
  eq(p('8').ok, false, 'счёт без /10 не принимается');
  eq(p('отлично').ok, false, 'словами счёт не принимается');
  eq(p('7/10', 'L1|L2|L3').ok, false, 'шаблон уровня «L1|L2|L3» отклонён');
  ok(/уровня/.test(p('7/10', 'L1|L2|L3').error), 'сказано, что не хватает уровня');
  eq(p('7/10', 'взят L2').ok, false, 'уровень с приписками не принимается');
  eq(p('7/10', 'l3').level, 'L3', 'литеральный уровень в нижнем регистре — принят');
});

describe('парсер B-12: markdown-обвес срезается', function () {
  var p = PROMPTS.parse([
    '**=== ИТОГ УРОКА B2.1 ===**',
    '**Пройдено:** наклон и системы',
    '**Уровень:** L2',
    '**Счёт:** 7/10',
    '*Слова (8–12):* slope — наклон; vertex — вершина',
    '`Долги:` путает знак наклона',
    '**Погашено:** нет',
    '__В разогрев:__ что такое slope?',
    '### Письмо: чистовик хороший',
    '**=== КОНЕЦ ===**'
  ].join('\n'));

  eq(p.ok, true, 'жирный markdown разобран');
  eq(p.score, 7, 'счёт из «**Счёт:** 7/10»');
  eq(p.level, 'L2', 'уровень из «**Уровень:** L2»');
  eq(p.topics, 'наклон и системы', 'темы без звёздочек');
  eq(p.words.length, 2, 'слова из «*Слова:*»');
  eq(p.debts.length, 1, 'долги из «`Долги:`»');
  eq(p.warmup.length, 1, 'разогрев из «__В разогрев:__»');
  eq(p.writing, 'чистовик хороший', 'заголовок «### Письмо:» тоже читается');

  var alt = PROMPTS.parse('=== ИТОГ УРОКА B1.1 ===\n**Счёт**: 8/10\n**Уровень**: L1\n=== КОНЕЦ ===');
  eq([alt.ok, alt.score, alt.level], [true, 8, 'L1'], 'вариант «**Счёт**: …» тоже проходит');

  var dash = PROMPTS.parse('=== ИТОГ УРОКА B1.1 ===\nСчёт: 8/10\nУровень: L1\n' +
    'Слова: y-intercept — точка пересечения\n=== КОНЕЦ ===');
  eq(dash.words[0], { en: 'y-intercept', ru: 'точка пересечения' }, 'дефис внутри слова не пострадал');
});

